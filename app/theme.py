def _ring_points(cx, cy, rx, ry, rot_deg, start_deg=0, end_deg=360, steps=None):
    """Sample points along a (possibly partial) ellipse centered at
    (cx, cy) and rotated by rot_deg -- used to build every tilted ring/arc
    in draw_logo_mark below. Tkinter's create_oval/create_arc only draw
    axis-aligned shapes, so a tilted one has to be built as a plain point
    list fed to create_line instead; like rounded_rect() above, this
    samples real trigonometric points rather than using
    create_line(..., smooth=True), which approximates a spline *near* its
    control points rather than through them (see rounded_rect's docstring
    for the visible artifacts that caused, on a Retina display in
    particular).

    Unlike rounded_rect's angle convention (0=east/90=north, with y
    flipped to compensate for the canvas's y-down coordinate space), this
    works entirely in plain screen/canvas coordinates with no flip, and
    angles/rotation match SVG's rotate() transform directly. That's
    because this mark's proportions were designed and approved as an SVG
    mockup first -- porting those numbers verbatim was the lower-risk way
    to reproduce the design exactly, rather than translating them into a
    different convention by hand.

    Returns a flat [x1, y1, x2, y2, ...] list, ready for
    canvas.create_line(*points, ...)."""
    if steps is None:
        steps = max(8, round(abs(end_deg - start_deg) / 5))
    rot = math.radians(rot_deg)
    cos_r, sin_r = math.cos(rot), math.sin(rot)
    points = []
    for i in range(steps + 1):
        theta = math.radians(start_deg + (end_deg - start_deg) * i / steps)
        x0 = rx * math.cos(theta)
        y0 = ry * math.sin(theta)
        points.append(cx + x0 * cos_r - y0 * sin_r)
        points.append(cy + x0 * sin_r + y0 * cos_r)
    return points


def draw_logo_mark(canvas, size=28, pad=1):
    """Draw the QUASAR mark: a clock-faced core sphere wrapped in a
    tilted, Saturn-style ring system with a bright shooting-star taper on
    its near edge, plus a scattering of small stars. Deliberately not an
    emoji or symbol-font glyph, since those aren't reliably available on
    every machine (headless/minimal Linux installs in particular).

    Tkinter has no native support for rotated ellipses, real alpha
    blending, or blur, so every tilted ring/arc here is a point-sampled
    line (see _ring_points above) and every "opacity" from the original
    design is faked with a solid color pre-blended toward whatever
    actually sits behind that shape -- the canvas's own background for
    anything drawn on empty space, or ACCENT for anything drawn over the
    opaque sphere -- via the _mix() helper near the top of this module.
    packaging/make_icons.py draws the same design again independently,
    using Pillow's real compositing and rotation for the packaged app
    icon; the two aren't shared code, so a future redesign needs both
    updated.

    Uses the module's live ACCENT (not a fixed color), so this header
    mark re-themes along with everything else when the user picks a
    different theme; make_icons.py's packaged icon stays a fixed brand
    blue instead, since that one can't change after the app is built."""
    canvas.delete("all")
    scale = (size - 2 * pad) / 120.0
    bg = PANEL_BG  # this canvas's own background -- see main_window.py's construction

    def X(x):
        return pad + x * scale

    def Y(y):
        return pad + y * scale

    def W(width):
        return max(1.0, width * scale)

    def line(points, **kwargs):
        canvas.create_line(*(X(p) if i % 2 == 0 else Y(p) for i, p in enumerate(points)), **kwargs)

    def polygon(points, **kwargs):
        canvas.create_polygon(*(X(p) if i % 2 == 0 else Y(p) for i, p in enumerate(points)), **kwargs)

    # ---- Saturn-style ring system (back pass, behind the sphere) -------
    ring_cx, ring_cy, ring_rot = 60, 66, -20
    line(_ring_points(ring_cx, ring_cy, 60, 11, ring_rot),
         fill=_mix(bg, ACCENT, 0.28), width=W(2), dash=(2, 5))
    line(_ring_points(ring_cx, ring_cy, 54, 9.5, ring_rot),
         fill=_mix(bg, ACCENT, 0.42), width=W(2.5))
    line(_ring_points(ring_cx, ring_cy, 48, 8, ring_rot),
         fill=_mix(bg, ACCENT, 0.5), width=W(5), capstyle="round")

    # ---- core sphere -----------------------------------------------------
    sx, sy, r = 60, 50, 25
    canvas.create_oval(X(sx - r), Y(sy - r), X(sx + r), Y(sy + r), fill=ACCENT, outline="")

    # ---- watch-face bezel: semi-transparent white over the sphere -------
    br = 19.5
    canvas.create_oval(X(sx - br), Y(sy - br), X(sx + br), Y(sy + br),
                        outline=_mix(ACCENT, "#FFFFFF", 0.3), width=W(1.5))

    # ---- clock hands, fixed at 10:10 (the classic "friendly" clock
    # position) -- the timesheet reference the halo design was missing.
    canvas.create_line(X(sx), Y(sy), X(52.6), Y(44.8), fill="white", width=W(3.6), capstyle="round")
    canvas.create_line(X(sx), Y(sy), X(72.1), Y(43), fill="white", width=W(3.6), capstyle="round")
    cr = 2.4
    canvas.create_oval(X(sx - cr), Y(sy - cr), X(sx + cr), Y(sy + cr), fill="white", outline="")

    # ---- the ring's front/near edge, tapering from dim to a bright
    # near-white point like a shooting star -- three nested partial arcs
    # sharing the same start angle, each shorter and brighter than the
    # last, each pre-blended against ACCENT (what they're actually drawn
    # over) instead of the canvas background.
    line(_ring_points(ring_cx, ring_cy, 48, 8, ring_rot, 20, 160),
         fill=_mix(ACCENT, "#6EA0FF", 0.55), width=W(4), capstyle="round")
    line(_ring_points(ring_cx, ring_cy, 48, 8, ring_rot, 20, 100),
         fill=_mix(ACCENT, "#B7D0FF", 0.8), width=W(3.5), capstyle="round")
    line(_ring_points(ring_cx, ring_cy, 48, 8, ring_rot, 20, 60),
         fill="#F3F8FF", width=W(3), capstyle="round")

    # ---- a scattered handful of stars for the "in space" feel -- each
    # sits on empty background, so blended toward `bg` rather than ACCENT.
    def sparkle(cx, cy, long_r, short_r, alpha):
        k = short_r * 0.70710678  # short_r at 45 degrees
        polygon([cx, cy - long_r, cx + k, cy - k, cx + long_r, cy,
                 cx + k, cy + k, cx, cy + long_r, cx - k, cy + k,
                 cx - long_r, cy, cx - k, cy - k],
                fill=_mix(bg, "#FFFFFF", alpha), outline="")

    sparkle(100, 18, 6, 2, 0.9)
    sparkle(14, 24, 3, 1, 0.55)
    sparkle(10, 100, 3.5, 1.2, 0.6)
    dot_r = 1.8
    canvas.create_oval(X(108 - dot_r), Y(102 - dot_r), X(108 + dot_r), Y(102 + dot_r),
                        fill=_mix(bg, "#FFFFFF", 0.5), outline="")


def draw_theme_swatch(canvas, theme_id: str, selected: bool, width=132, height=88):
    """Draw a small live preview card for one theme onto `canvas`, using
    that theme's own palette directly (not the app's currently-active
    globals above) -- this is what lets Settings show every preset side by
    side regardless of which one is actually active right now. Works for
    "custom" exactly like any other id -- get_theme() builds its palette
    live from the user's current seed colors either way.

    Places and Atmosphere cards get a tiny scenic illustration (sky, sun,
    skyline) so the picker reads like TickTick's theme grid. Other palettes
    keep the miniature calendar: an inset panel and two time-block bars.
    """
    canvas.delete("all")
    info = get_theme(theme_id)
    p = info["palette"]
    category = info.get("category") or ""

    place_rounded_rect(canvas, 1, 1, width - 1, height - 1, radius=10,
                       fill=p["APP_BG"], outline="", background=p["APP_BG"])

    if category in ("Places", "Atmosphere", "Glass"):
        _draw_scenic_mini(canvas, p, theme_id, width, height)
    else:
        card_pad = 10
        card_top = 10
        place_rounded_rect(canvas, card_pad, card_top, width - card_pad, height - 12,
                           radius=6, fill=p["PANEL_BG"], outline=p["BORDER"], width=1,
                           background=p["APP_BG"])
        bar_x = card_pad + 8
        bar_w = width - 2 * (card_pad + 8)
        place_rounded_rect(canvas, bar_x, card_top + 12, bar_x + bar_w, card_top + 26,
                           radius=3, fill=p["ACCENT"], outline="", background=p["PANEL_BG"])
        place_rounded_rect(canvas, bar_x, card_top + 32, bar_x + bar_w * 0.62, card_top + 46,
                           radius=3, fill=p["BORDER_STRONG"], outline="", background=p["PANEL_BG"])

    outline_color = p["ACCENT"] if selected else p["BORDER_STRONG"]
    outline_width = 3 if selected else 1
    rounded_rect(canvas, 1, 1, width - 1, height - 1, radius=10, outline=outline_color,
                 width=outline_width, fill="")

    if selected:
        badge_r = 9
        bx, by = width - 14, 14
        canvas.create_oval(bx - badge_r, by - badge_r, bx + badge_r, by + badge_r,
                            fill=p["ACCENT"], outline="")
        canvas.create_line(bx - 4, by, bx - 1, by + 3, bx + 4, by - 4,
                            fill="white", width=2, capstyle="round", joinstyle="round")


def _draw_scenic_mini(canvas, p, theme_id: str, width: int, height: int):
    """Tiny sky / sun / skyline using only this palette's colors."""
    sky = p["APP_BG"]
    ground = p["PANEL_BG"]
    accent = p["ACCENT"]
    dark = _is_dark(p["PANEL_BG"])
    horizon = int(height * 0.58)

    canvas.create_rectangle(6, 6, width - 6, horizon, fill=sky, outline="")
    canvas.create_rectangle(6, horizon, width - 6, height - 6, fill=ground, outline="")

    seed = sum(ord(c) for c in theme_id)
    sr = 9 + (seed % 5)
    sx = width - 22 - (seed % 18)
    sy = 18 + (seed % 10)
    canvas.create_oval(sx - sr, sy - sr, sx + sr, sy + sr, fill=accent, outline="")

    if dark:
        for i in range(5):
            dx = 12 + ((seed * (i + 3)) % (width - 40))
            dy = 12 + ((seed * (i + 7)) % 22)
            canvas.create_oval(dx, dy, dx + 2, dy + 2, fill=p["TEXT_MUTED"], outline="")

    n = 5 + (seed % 3)
    x = 8
    gap = 2
    avail = width - 16 - gap * (n - 1)
    bw = max(8, avail // n)
    for i in range(n):
        bh = 10 + ((seed * (i + 5) * 13) % 26)
        x0 = x + i * (bw + gap)
        canvas.create_rectangle(x0, horizon - bh, x0 + bw, horizon + 2,
                                fill=_mix(ground, accent, 0.22 if i % 2 else 0.08),
                                outline="")
    canvas.create_polygon(
        6, horizon + 6,
        18 + (seed % 20), horizon - 8,
        40 + (seed % 30), horizon + 4,
        width - 6, horizon + 8,
        width - 6, height - 6,
        6, height - 6,
        fill=_mix(ground, p["TEXT_PRIMARY"], 0.06), outline="")


def rounded_rect(canvas, x1, y1, x2, y2, radius: float = 8, exponent: float = 4.0, **kwargs):
    """Draw a rounded rectangle on `canvas`, as a single polygon item.

    This has gone through two worse designs before landing here, both
    visible as real "artifacts" reported on real hardware (a Retina
    MacBook) that a plain-DPI Linux test environment never surfaced:

    1. Originally a single `create_polygon(..., smooth=True)` -- Tk's
       polygon smoothing approximates a spline *near* its control points
       rather than through them, which could leave a sliver of the
       canvas's flat background color poking out right at a corner.
    2. Then rewritten as several composited items per shape (quarter-circle
       "pieslice" arcs for the fill, plain arc outlines for the border,
       plus rectangles/lines for the straight edges) to get true circular
       corners. That fixed (1) but traded it for a worse, platform-specific
       problem: Tk's `create_arc` outline rendering (particularly with a
       thicker `width`, as the Settings theme-picker's selected-swatch ring
       uses) can draw past the arc's own bounding box at the start/end caps
       on some Tk builds -- visible as a small square notch poking out at
       a corner, exactly where the previous approach left a gap instead.

    This version samples real trigonometric points around each corner's
    true circular arc (no spline approximation) and draws the WHOLE shape
    -- all four corners and the straight edges between them -- as one
    `create_polygon` call, which natively supports fill AND outline
    together. One item means no seam between separately-drawn pieces is
    possible, and no per-item arc/line stroke-cap quirks either.

    `exponent` controls the corner *curve family*, not just its radius.
    2.0 is a true circular arc (the original design). Apple's "continuous
    corner" / squircle rounding used throughout iOS and macOS is smoother
    than a circular arc -- it keeps curving into the straight edge instead
    of meeting it at an abrupt tangent point -- and is commonly approximated
    with a superellipse of degree ~4-5. This defaults to 4.0 so every
    rounded shape in the app (buttons, cards, the calendar's own corners)
    reads as "Apple-style" without every call site needing to opt in.

    Returns the created item id (useful for the one caller --
    calendar_view._draw_entry -- that stacks its label text via
    `tag_raise(text_item, this_return_value)`).
    """
    x1, x2 = (x1, x2) if x1 <= x2 else (x2, x1)
    y1, y2 = (y1, y2) if y1 <= y2 else (y2, y1)
    radius = max(0.0, min(radius, (x2 - x1) / 2, (y2 - y1) / 2))

    if radius <= 0:
        return canvas.create_rectangle(x1, y1, x2, y2, **kwargs)

    points = rounded_rect_points(x1, y1, x2, y2, radius=radius, exponent=exponent)
    return canvas.create_polygon(points, **kwargs)


def rounded_rect_points(x1, y1, x2, y2, radius: float = 8, exponent: float = 4.0,
                        steps=None):
    """Flat [x, y, ...] list for a superellipse rounded rect.

    Live calendar previews reuse the same point count every motion
    (`steps` fixed) so `canvas.coords` can reshape the polygon without
    recreating it — a PhotoImage per mouse-pixel would hitch, and a
    plain `create_rectangle` looks stair-stepped on Retina.
    """
    x1, x2 = (x1, x2) if x1 <= x2 else (x2, x1)
    y1, y2 = (y1, y2) if y1 <= y2 else (y2, y1)
    radius = max(0.0, min(float(radius), (x2 - x1) / 2, (y2 - y1) / 2))
    if radius <= 0:
        return [x1, y1, x2, y1, x2, y2, x1, y2]
    corners = [
        (x2 - radius, y1 + radius, 90, 0),
        (x2 - radius, y2 - radius, 0, -90),
        (x1 + radius, y2 - radius, -90, -180),
        (x1 + radius, y1 + radius, -180, -270),
    ]
    if steps is None:
        steps = max(18, int(radius * 2.5))
    steps = max(4, int(steps))
    power = 2.0 / exponent
    points = []
    for cx, cy, start_deg, end_deg in corners:
        for i in range(steps + 1):
            deg = start_deg + (end_deg - start_deg) * i / steps
            rad = math.radians(deg)
            cos_v = math.cos(rad)
            sin_v = math.sin(rad)
            points.append(cx + radius * math.copysign(abs(cos_v) ** power, cos_v))
            points.append(cy - radius * math.copysign(abs(sin_v) ** power, sin_v))
    return points


def _sdf_rounded_rect(px: float, py: float, x1: float, y1: float,
                      x2: float, y2: float, radius: float) -> float:
    """Signed distance to a rounded rectangle (negative = inside)."""
    cx = (x1 + x2) * 0.5
    cy = (y1 + y2) * 0.5
    half_w = (x2 - x1) * 0.5
    half_h = (y2 - y1) * 0.5
    dx = abs(px - cx) - (half_w - radius)
    dy = abs(py - cy) - (half_h - radius)
    ox = dx if dx > 0.0 else 0.0
    oy = dy if dy > 0.0 else 0.0
    inside = dx if dx > dy else dy
    if inside > 0.0:
        inside = 0.0
    return math.hypot(ox, oy) + inside - radius


def _coverage(distance: float) -> float:
    """Smoothstep across ~2 logical pixels.

    PhotoImages are 1 Tk-pixel and get doubled on Retina, so a 1px
    coverage ramp becomes a 2px stair. A wider smoothstep stays round
    after that blit.
    """
    width = 2.0
    t = 0.5 - distance / width
    if t <= 0.0:
        return 0.0
    if t >= 1.0:
        return 1.0
    return t * t * (3.0 - 2.0 * t)


def _average_hex(colors) -> str:
    n = len(colors) or 1
    acc = [0, 0, 0]
    for color in colors:
        rgb = _hex_to_rgb(color)
        acc[0] += rgb[0]
        acc[1] += rgb[1]
        acc[2] += rgb[2]
    return _rgb_to_hex((acc[0] / n, acc[1] / n, acc[2] / n))


def _aa_pixel(px: float, py: float, box, radius: float, fill: str,
              background: str, outline: str, stroke: float) -> str:
    x1, y1, x2, y2 = box
    outer = _sdf_rounded_rect(px, py, x1, y1, x2, y2, radius)
    if stroke > 0.0 and outline:
        inner_r = max(0.0, radius - stroke)
        inner = _sdf_rounded_rect(
            px, py, x1 + stroke, y1 + stroke, x2 - stroke, y2 - stroke, inner_r)
        a_outer = _coverage(outer)
        if a_outer <= 0.0:
            return background
        color = outline if a_outer >= 1.0 else _mix(background, outline, a_outer)
        a_inner = _coverage(inner)
        if a_inner <= 0.0:
            return color
        return fill if a_inner >= 1.0 else _mix(color, fill, a_inner)
    a = _coverage(outer)
    if a <= 0.0:
        return background
    if a >= 1.0:
        return fill
    return _mix(background, fill, a)


def _make_aa_image(width: int, height: int, radius: float, fill: str,
                   background: str, outline: str, stroke: float, box=None,
                   backgrounds=None, fill_end: str = "", glow: float = 0.0):
    import tkinter as tk

    width = max(1, int(width))
    height = max(1, int(height))
    fill = (fill or "#000000").upper()
    background = (background or "#000000").upper()
    outline = (outline or "").upper()
    fill_end = (fill_end or "").upper()
    if fill_end == fill:
        fill_end = ""
    glow = max(0.0, float(glow or 0.0))
    if box is None:
        if glow > 0.0:
            box = (glow + 0.5, glow + 0.5, width - glow - 0.5, height - glow - 0.5)
        else:
            box = (0.5, 0.5, width - 0.5, height - 0.5)
    if backgrounds is None:
        nw = ne = sw = se = background
        uniform = True
    else:
        nw, ne, sw, se = [
            (c or background or "#000000").upper() for c in backgrounds]
        uniform = nw == ne == sw == se
        if uniform:
            background = nw
    key = (width, height, round(float(radius), 2), fill, fill_end,
           (nw, ne, sw, se) if not uniform else background, outline,
           round(float(stroke), 2), tuple(round(v, 2) for v in box),
           round(glow, 2))
    cached = _AA_IMAGE_CACHE.get(key)
    if cached is not None:
        return cached
    span = max(width - 1, 1)

    def fill_at(px):
        if not fill_end:
            return fill
        t = max(0.0, min(1.0, (px - 0.5) / span))
        return _mix(fill, fill_end, t)

    rows = []
    def sample(px, py, bg=background):
        def one(sx, sy):
            pix_fill = fill_at(sx)
            dist = _sdf_rounded_rect(sx, sy, box[0], box[1], box[2], box[3], radius)
            if stroke > 0.0 and outline and glow <= 0.0:
                return _aa_pixel(sx, sy, box, radius, pix_fill, bg, outline, stroke)
            a = _coverage(dist)
            glow_a = 0.0
            if glow > 0.0 and dist > 0.0:
                t = max(0.0, 1.0 - dist / glow)
                glow_a = t * t * 0.40
            m = a if a >= glow_a else glow_a
            if m <= 0.0:
                return bg
            if m >= 1.0:
                return pix_fill
            return _mix(bg, pix_fill, m)

        dist = _sdf_rounded_rect(px, py, box[0], box[1], box[2], box[3], radius)
        # Glow already falls off smoothly; 9-tap only the pill's own edge
        # so Retina doesn't turn that ring into a broken black hairline.
        if glow > 0.0 and dist > 2.4:
            return one(px, py)
        centre = one(px, py)
        if abs(dist) > 2.4 and not (stroke > 0.0 and outline and abs(dist) < stroke + 2.4):
            return centre
        colors = [
            one(px + dx, py + dy)
            for dx, dy in (
                (-0.33, -0.33), (0.0, -0.33), (0.33, -0.33),
                (-0.33, 0.0), (0.0, 0.0), (0.33, 0.0),
                (-0.33, 0.33), (0.0, 0.33), (0.33, 0.33),
            )
        ]
        return _average_hex(colors)

    if uniform:
        for y in range(height):
            py = y + 0.5
            cells = [sample(x + 0.5, py) for x in range(width)]
            rows.append("{" + " ".join(cells) + "}")
    else:
        mid_x = width / 2.0
        mid_y = height / 2.0
        for y in range(height):
            py = y + 0.5
            row_left = nw if py < mid_y else sw
            row_right = ne if py < mid_y else se
            cells = []
            for x in range(width):
                bg = row_left if (x + 0.5) < mid_x else row_right
                cells.append(sample(x + 0.5, py, bg))
            rows.append("{" + " ".join(cells) + "}")
    img = tk.PhotoImage(width=width, height=height)
    img.put(" ".join(rows))
    if len(_AA_IMAGE_CACHE) >= _AA_IMAGE_CACHE_MAX:
        _AA_IMAGE_CACHE.clear()
    _AA_IMAGE_CACHE[key] = img
    return img


def rounded_rect_image(width: int, height: int, radius: float, fill: str,
                       background: str, outline: str = "", outline_width: float = 1.0,
                       fill_end: str = "", glow: float = 0.0):
    """A PhotoImage of a coverage-antialiased rounded rect.

    Tk's `create_polygon` fill is not antialiased, so on a Retina Mac the
    corner of a 32px button looks stair-stepped. Painting the shape into
    a PhotoImage (blending against `background` per pixel) is how we get
    a smooth edge without extra dependencies, while still using whatever
    fill/outline the current theme asked for.

    `fill_end` paints a left-to-right gradient (Quasar's cyan→violet
    Accent buttons). Empty means a flat fill.

    `glow` is extra pixels of quadratic falloff outside the pill — light
    coming off the fill, not a second stacked button.

    Callers must keep the returned image alive (a widget attribute) so
    Tk doesn't garbage-collect it out from under the canvas.
    """
    stroke = outline_width if outline else 0.0
    return _make_aa_image(
        width, height, radius, fill, background, outline, stroke,
        fill_end=fill_end, glow=glow)


def _keep_aa_image(canvas, img):
    kept = getattr(canvas, "_aa_images", None)
    if kept is None:
        canvas._aa_images = [img]
        return
    kept.append(img)
    if len(kept) > 480:
        canvas._aa_images = kept[-240:]


def _with_transparent_outside(img, background: str):
    """Copy of `img` whose exact-background pixels are see-through.

    Tk widgets are always square; the leftover corner triangles are
    painted in `background`. On the calendar canvas those triangles
    stamp GRID_BG over the today tint. Punching them out lets the grid
    show through so a drag card matches a settled block.
    """
    if not background or not str(background).startswith("#") or len(background) < 7:
        return img
    try:
        r = int(background[1:3], 16)
        g = int(background[3:5], 16)
        b = int(background[5:7], 16)
        out = img.copy()
        w, h = int(out.width()), int(out.height())
        # Only the rounded-rect's outside ring can be the blend color;
        # skipping the interior keeps tall time-block punches cheap.
        band = min(w, h) if min(w, h) <= 40 else 22
        for y in range(h):
            edge_y = y < band or y >= h - band
            for x in range(w):
                if not edge_y and band <= x < w - band:
                    continue
                px = out.get(x, y)
                if isinstance(px, str):
                    parts = px.replace(",", " ").split()
                    got = tuple(int(float(p)) for p in parts[:3])
                else:
                    got = tuple(int(v) for v in px[:3])
                if got == (r, g, b):
                    out.transparency_set(x, y, True)
        return out
    except Exception:
        return img


def _maybe_transparent(img, background: str, transparent_outside: bool):
    if not transparent_outside:
        return img
    return _with_transparent_outside(img, background)


def _corner_patch(corner: str, size: int, radius: float, fill: str,
                  background: str, outline: str, stroke: float):
    far = 4096.0
    if corner == "nw":
        box = (0.5, 0.5, far, far)
    elif corner == "ne":
        box = (size - far, 0.5, size - 0.5, far)
    elif corner == "se":
        box = (size - far, size - far, size - 0.5, size - 0.5)
    else:
        box = (0.5, size - far, far, size - 0.5)
    return _make_aa_image(size, size, radius, fill, background, outline, stroke, box)


def place_rounded_rect(canvas, x1, y1, x2, y2, radius: float = 8, fill: str = "",
                       outline: str = "", width: float = 1, background: str = None,
                       corner_backgrounds=None, full: bool = False,
                       transparent_outside: bool = False, **item_kwargs):
    """Draw a coverage-antialiased rounded rect on `canvas`.

    Small chips (buttons, thumbs, swatches, short time blocks) are a
    single PhotoImage. Large cards use four cached corner patches plus
    rectangles so a sash-drag doesn't re-rasterize the whole panel.

    `corner_backgrounds` is an optional dict of nw/ne/sw/se hex colors used
    when the card floats over more than one surface (the Timer QDM menu
    sits on the timer bar at the top and the timesheet at the bottom).
    Without it, every cut-off corner blends toward a single `background`,
    which reads as a black or white square halo if that color isn't what's
    actually behind the card.

    Returns the item ids created (last id is a stable raise-target).
    Falls back to the polygon `rounded_rect` if PhotoImage isn't usable.
    """
    if x2 < x1:
        x1, x2 = x2, x1
    if y2 < y1:
        y1, y2 = y2, y1
    if background is None:
        try:
            background = canvas.cget("bg") or PANEL_BG
        except Exception:
            background = PANEL_BG

    def _corner_bg(corner: str) -> str:
        if corner_backgrounds:
            color = corner_backgrounds.get(corner)
            if color:
                return color
        return background

    nw, ne, sw, se = _corner_bg("nw"), _corner_bg("ne"), _corner_bg("sw"), _corner_bg("se")
    uniform = nw == ne == sw == se
    paint_bg = nw
    fill = fill or paint_bg
    stroke = float(width) if outline else 0.0
    ox, oy = int(round(x1)), int(round(y1))
    w, h = max(1, int(round(x2 - x1))), max(1, int(round(y2 - y1)))
    radius = max(0.0, min(float(radius), w / 2.0, h / 2.0))
    bgs = None if uniform else (nw, ne, sw, se)
    try:
        # Tall calendar blocks used to trip the "four tiny corner patches"
        # path and look pixelated when you stretched duration. `full=True`
        # keeps one coverage-AA image for the whole shape.
        if full or w * h <= 48000:
            img = _maybe_transparent(
                _make_aa_image(
                    w, h, radius, fill, paint_bg, outline, stroke, backgrounds=bgs),
                paint_bg, transparent_outside)
            _keep_aa_image(canvas, img)
            return [canvas.create_image(ox, oy, image=img, anchor="nw", **item_kwargs)]

        patch = max(2, int(math.ceil(radius)) + 2)
        if patch * 2 >= min(w, h):
            img = _maybe_transparent(
                _make_aa_image(
                    w, h, radius, fill, paint_bg, outline, stroke, backgrounds=bgs),
                paint_bg, transparent_outside)
            _keep_aa_image(canvas, img)
            return [canvas.create_image(ox, oy, image=img, anchor="nw", **item_kwargs)]

        ids = []
        for corner, px, py in (
            ("nw", ox, oy),
            ("ne", ox + w - patch, oy),
            ("sw", ox, oy + h - patch),
            ("se", ox + w - patch, oy + h - patch),
        ):
            img = _corner_patch(
                corner, patch, radius, fill, _corner_bg(corner), outline, stroke)
            _keep_aa_image(canvas, img)
            ids.append(canvas.create_image(px, py, image=img, anchor="nw", **item_kwargs))
        sw = int(round(stroke)) if stroke else 0
        # Straight edges: outer hairline in outline, the rest in fill.
        ids.append(canvas.create_rectangle(
            ox + patch, oy + sw, ox + w - patch, oy + h - sw, fill=fill, outline="", **item_kwargs))
        ids.append(canvas.create_rectangle(
            ox + sw, oy + patch, ox + w - sw, oy + h - patch, fill=fill, outline="", **item_kwargs))
        if sw and outline:
            ids.append(canvas.create_rectangle(
                ox + patch, oy, ox + w - patch, oy + sw, fill=outline, outline="", **item_kwargs))
            ids.append(canvas.create_rectangle(
                ox + patch, oy + h - sw, ox + w - patch, oy + h, fill=outline, outline="", **item_kwargs))
            ids.append(canvas.create_rectangle(
                ox, oy + patch, ox + sw, oy + h - patch, fill=outline, outline="", **item_kwargs))
            ids.append(canvas.create_rectangle(
                ox + w - sw, oy + patch, ox + w, oy + h - patch, fill=outline, outline="", **item_kwargs))
        return ids
    except Exception:
        item = rounded_rect(
            canvas, x1, y1, x2, y2, radius=radius, fill=fill,
            outline=outline, width=width, **item_kwargs)
        return [item]
