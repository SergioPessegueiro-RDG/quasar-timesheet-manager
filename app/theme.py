# ---------------------------------------------------------------------------
# Color math -- small helpers used only to derive a full ~24-color palette
# from a handful of seed colors (see derive_palette below).
# ---------------------------------------------------------------------------
def _hex_to_rgb(hex_color: str):
    h = hex_color.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def _rgb_to_hex(rgb) -> str:
    return "#{:02X}{:02X}{:02X}".format(*(max(0, min(255, round(c))) for c in rgb))


def _mix(color_a: str, color_b: str, t: float) -> str:
    """Blend from color_a toward color_b by fraction t (0 = color_a,
    1 = color_b), in plain sRGB. Not perceptually uniform, but plenty
    good enough at the small t values every derived color below uses,
    and it's what the hand-tuned originals turn out to approximate too."""
    a, b = _hex_to_rgb(color_a), _hex_to_rgb(color_b)
    return _rgb_to_hex(a[i] + (b[i] - a[i]) * t for i in range(3))


def _darken(color: str, amount: float) -> str:
    """Multiply each channel toward black by `amount` (0 = unchanged,
    1 = black) -- used for ACCENT_HOVER, a plain darken rather than a mix
    toward some other color."""
    r, g, b = _hex_to_rgb(color)
    factor = 1.0 - amount
    return _rgb_to_hex((r * factor, g * factor, b * factor))


def _is_dark(color: str) -> bool:
    """Perceptual-ish luminance check used only to decide which side of a
    couple of mode-dependent rules (FIELD_BG, SURFACE, default danger/now
    -line colors) a seed palette falls on -- there's no separate light/
    dark toggle the user sets; it's inferred from the panel color itself."""
    r, g, b = _hex_to_rgb(color)
    luminance = 0.299 * r + 0.587 * g + 0.114 * b
    return luminance < 128


