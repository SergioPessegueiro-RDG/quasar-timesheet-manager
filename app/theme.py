# Dark text used on a bright/light time-block or chart-slice color --
# matches the near-black summary_panel.py's own pie-chart labels already
# used for exactly this problem, reused here rather than inventing a
# second, slightly different near-black.
BLOCK_TEXT_DARK = "#1A1A1A"
BLOCK_TEXT_LIGHT = "#FFFFFF"


def block_text_color(bg_hex: str) -> str:
    """Pick a readable label color for text drawn on top of an arbitrary
    fill color -- calendar_view.py's time-block labels
    (_draw_entry/_update_entry_drag_preview) and summary_panel.py's pie-
    chart slice labels both use this. Unlike ACCENT -- which every
    curated theme picks specifically so plain white text always reads on
    it -- these colors come from whatever a Project was given (one of
    config.DEFAULT_PROJECT_COLORS, or any custom hex the user picked in
    ProjectPanel), independent of the active theme, which spans plenty of
    pale/bright colors white text disappears on. Reuses the same
    luminance check _is_dark() already uses for palette derivation."""
    return BLOCK_TEXT_LIGHT if _is_dark(bg_hex) else BLOCK_TEXT_DARK


def _saturation(color: str) -> float:
    r, g, b = (c / 255.0 for c in _hex_to_rgb(color))
    mx, mn = max(r, g, b), min(r, g, b)
    if mx <= 1e-6:
        return 0.0
    return (mx - mn) / mx


def _desaturate(color: str, amount: float) -> str:
    r, g, b = _hex_to_rgb(color)
    gray = 0.299 * r + 0.587 * g + 0.114 * b
    return _rgb_to_hex((
        r + (gray - r) * amount,
        g + (gray - g) * amount,
        b + (gray - b) * amount,
    ))


def block_fill(color: str, surface: str = None) -> str:
    """The color actually painted for a project on the calendar/sidebar.

    Stored project hexes are often neon (Material defaults, a custom
    picker). Mixing them toward the current surface and pulling saturation
    keeps hue identity while sitting with cream/charcoal chrome.
    """
    raw = (color or "").strip()
    if not raw.startswith("#"):
        raw = ACCENT
    surface = surface or GRID_BG
    sat = _saturation(raw)
    softened = _desaturate(raw, 0.22 * sat)
    toward = 0.16 + 0.30 * sat
    if _is_dark(surface):
        toward *= 0.72
    return _mix(softened, surface, toward)


def calendar_block_fill(color: str, surface: str = None) -> str:
    """Tinted glass over the grid — Apple Calendar, not a pastel sticker.

    Dark chrome keeps a dark wash of the project hue so the block sits
    *in* the UI; light chrome gets a pale wash. Title ink is a separate
    chromatic color (see calendar_block_title_color), the way Reminders
    and Calendar color the label rather than dropping black on mint.
    """
    hue = _project_hex(color)
    surface = surface or GRID_BG
    washed = _desaturate(hue, 0.10)
    if _is_dark(surface):
        return _mix(surface, washed, 0.40)
    return _mix(surface, washed, 0.30)


def calendar_block_title_color(color: str, fill: str = None) -> str:
    """Project hue as the title: lifted on dark tints, deepened on light."""
    hue = _project_hex(color)
    fill = fill or calendar_block_fill(hue)
    if _is_dark(fill):
        lifted = _mix(_desaturate(hue, 0.06), "#FFFFFF", 0.40)
        if _is_dark(lifted):
            lifted = _mix(lifted, "#FFFFFF", 0.40)
        return lifted
    deepened = _mix(hue, BLOCK_TEXT_DARK, 0.22)
    if not _is_dark(deepened):
        deepened = _mix(deepened, BLOCK_TEXT_DARK, 0.35)
    return deepened


def calendar_block_notes_color(color: str, fill: str = None) -> str:
    """Notes recede: same hue as the title, mixed back toward the fill."""
    fill = fill or calendar_block_fill(color)
    title = calendar_block_title_color(color, fill)
    return _mix(title, fill, 0.32)


def calendar_block_rail_color(color: str, fill: str = None) -> str:
    """Left accent on the tinted chip — the saturated identity stripe."""
    hue = _project_hex(color)
    fill = fill or calendar_block_fill(hue)
    if _is_dark(fill):
        return _mix(hue, "#FFFFFF", 0.20)
    return _mix(hue, BLOCK_TEXT_DARK, 0.08)


def unsent_label_color(block_fill: str, project_color: str = None) -> str:
    """Dusty red caption that follows the block's ink, not a Danger pill."""
    if project_color:
        ink = calendar_block_notes_color(project_color, block_fill)
    else:
        ink = block_text_color(block_fill)
    return _mix(DANGER, ink, 0.50)


def _project_hex(color: str) -> str:
    raw = (color or "").strip()
    return raw if raw.startswith("#") else ACCENT


def overlay_fill(surface: str = None) -> str:
    """Wash used for imported calendar meetings -- a guide, not a logged
    block. Mixes the accent toward the grid so it stays visible on light
    and dark themes without competing with real time entries on top."""
    surface = surface or GRID_BG
    return _mix(ACCENT, surface, 0.82)


def overlay_outline(surface: str = None) -> str:
    surface = surface or GRID_BG
    return _mix(ACCENT, surface, 0.62)


def overlay_text_color() -> str:
    return TEXT_MUTED


def derive_palette(app_bg: str, panel_bg: str, text_primary: str, accent: str,
                    danger: str = None, now_line: str = None,
                    accent_b: str = None) -> dict:
    """Build a full ~24-color palette from four required seed colors (an
    app background, a panel/card background, a primary text color, and an
    accent) plus two optional ones (a danger/delete red and a "now" line
    color -- sensible mode-appropriate defaults are used if omitted).

    `accent_b` is an optional second stop for Accent buttons (cyan→violet
    on the Quasar theme). When omitted it matches `accent`, so every
    other palette stays a flat fill.
    """
    dark = _is_dark(panel_bg)
    if danger is None:
        danger = "#E5484D" if dark else "#D6334C"
    if now_line is None:
        now_line = "#FF9500" if dark else "#FF5A36"
    if accent_b is None:
        accent_b = accent

    field_bg = _mix(panel_bg, text_primary, 0.035) if dark else panel_bg
    accent_hover = _darken(accent, 0.17)
    accent_soft = _mix(panel_bg, accent, 0.11)
    accent_mid = accent if accent_b.upper() == accent.upper() else _mix(accent, accent_b, 0.5)

    return {
        "APP_BG": app_bg,
        "PANEL_BG": panel_bg,
        "BORDER": _mix(panel_bg, text_primary, 0.065),
        "BORDER_STRONG": _mix(panel_bg, text_primary, 0.12),
        "TEXT_PRIMARY": text_primary,
        "TEXT_SECONDARY": _mix(text_primary, panel_bg, 0.38),
        "TEXT_MUTED": _mix(text_primary, panel_bg, 0.63),
        "ACCENT": accent,
        "ACCENT_B": accent_b,
        "ACCENT_HOVER": accent_hover,
        "ACCENT_SOFT": accent_soft,
        "DANGER": danger,
        "DANGER_SOFT": _mix(panel_bg, danger, 0.08),
        "DANGER_SOFT_ACTIVE": _mix(panel_bg, danger, 0.16),
        "GRID_LINE": _mix(panel_bg, text_primary, 0.04),
        "GRID_LINE_HOUR": _mix(panel_bg, text_primary, 0.10),
        "HEADER_BG": _mix(panel_bg, text_primary, 0.045),
        "TODAY_TINT": _mix(panel_bg, accent_mid, 0.18) if dark else _mix(panel_bg, accent_mid, 0.12),
        "NOW_LINE": now_line,
        "BLOCK_BORDER": panel_bg,
        "SELECTION_OUTLINE": text_primary,
        "PREVIEW_FILL": accent,
        "PREVIEW_OUTLINE": accent_hover,
        "FIELD_BG": field_bg,
        "SURFACE": field_bg if dark else app_bg,
        "GRID_BG": _mix(panel_bg, text_primary, 0.025) if dark else _mix(app_bg, panel_bg, 0.35),
    }


