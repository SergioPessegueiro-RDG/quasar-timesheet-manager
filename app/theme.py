_FONT_FAMILY = None


def resolve_font_family(root=None) -> str:
    """Pick the best-looking sans-serif font available on this machine.

    Must be called after a Tk root exists (tkfont.families() needs one).
    Cached after the first call.
    """
    global _FONT_FAMILY
    if _FONT_FAMILY is not None:
        return _FONT_FAMILY
    preferred = ["Segoe UI", "SF Pro Text", "Helvetica Neue", "Helvetica",
                 "Ubuntu", "Cantarell", "Noto Sans", "Arial", "DejaVu Sans"]
    try:
        available = set(tkfont.families(root))
    except Exception:
        available = set()
    for name in preferred:
        if name in available:
            _FONT_FAMILY = name
            break
    else:
        _FONT_FAMILY = "TkDefaultFont"
    return _FONT_FAMILY


def font(root=None, size=10, weight="normal"):
    return (resolve_font_family(root), size, weight)


def apply_theme(root):
    """Configure global widget defaults + ttk styles for the whole app,
    using whatever palette set_theme() last selected. Safe to call again
    after switching themes -- ttk widgets re-render immediately since ttk
    styles are looked up dynamically; plain tk widgets do not and must be
    rebuilt separately (see MainWindow._apply_theme_and_rebuild)."""
    family = resolve_font_family(root)

    root.configure(bg=APP_BG)
    # Sets the default font for every classic Tk widget (Label, Button,
    # Text, Listbox, Menu, ...) app-wide in one shot.
    root.option_add("*Font", (family, 10))
    root.option_add("*Menu.background", PANEL_BG)
    root.option_add("*Menu.foreground", TEXT_PRIMARY)
    root.option_add("*Menu.activeBackground", ACCENT_SOFT)
    root.option_add("*Menu.activeForeground", ACCENT)
    root.option_add("*Menu.borderWidth", 1)

    # A ttk.Combobox's dropdown list is a plain classic-Tk Listbox under the
    # hood, which does NOT pick up ttk styling -- left alone it renders with
    # Tk's own default colors (typically black-on-white) regardless of
    # theme, which stands out as an unreadable/jarring flash against a dark
    # panel. Themed explicitly here so every dropdown (Activity, Day,
    # Start/End time, Theme picker, etc.) matches whichever theme is active.
    root.option_add("*TCombobox*Listbox.background", FIELD_BG)
    root.option_add("*TCombobox*Listbox.foreground", TEXT_PRIMARY)
    root.option_add("*TCombobox*Listbox.selectBackground", ACCENT)
    root.option_add("*TCombobox*Listbox.selectForeground", "#FFFFFF")

    style = ttk.Style(root)
    try:
        style.theme_use("clam")
    except Exception:
        pass

    style.configure("TFrame", background=PANEL_BG)
    style.configure("App.TFrame", background=APP_BG)
    style.configure("Card.TFrame", background=PANEL_BG)

    style.configure("TLabel", background=PANEL_BG, foreground=TEXT_PRIMARY, font=(family, 10))
    style.configure("Secondary.TLabel", background=PANEL_BG, foreground=TEXT_SECONDARY, font=(family, 9))
    style.configure("Heading.TLabel", background=PANEL_BG, foreground=TEXT_PRIMARY, font=(family, 18, "bold"))

    # Primary (accent) button
    style.configure("Accent.TButton", background=ACCENT, foreground="white",
                     font=(family, 10, "bold"), padding=(14, 8), borderwidth=0, relief="flat")
    style.map("Accent.TButton",
              background=[("active", ACCENT_HOVER), ("pressed", ACCENT_HOVER)],
              foreground=[("disabled", TEXT_MUTED)])

    # Secondary (neutral) button. Idle fill is SURFACE, not APP_BG -- APP_BG
    # is the app's own base/outermost layer, darker than the PANEL_BG these
    # buttons actually sit on in every dark theme, which made them read as a
    # dim, sunken notch instead of a button. SURFACE is deliberately a step
    # *lighter* than PANEL_BG in dark themes (mirroring how BORDER/
    # BORDER_STRONG already correctly lighten further on hover/press) while
    # keeping the original APP_BG look for light themes, where a slightly
    # darker idle fill reads fine. See widgets._BUTTON_STYLES for the actual
    # hand-drawn RoundedButton this app renders (this ttk style is now
    # unused directly but kept in sync so it isn't a stale trap later).
    style.configure("Secondary.TButton", background=SURFACE, foreground=TEXT_PRIMARY,
                     font=(family, 10), padding=(10, 6), borderwidth=0, relief="flat")
    style.map("Secondary.TButton", background=[("active", BORDER), ("pressed", BORDER_STRONG)])

    # Small nav (‹ Today ›) buttons -- same reasoning as Secondary above:
    # hover should get more prominent than idle, which means lighter (not
    # darker) once the surrounding panel is itself dark.
    style.configure("Nav.TButton", background=PANEL_BG, foreground=TEXT_PRIMARY,
                     font=(family, 10), padding=(8, 5), borderwidth=1, relief="flat")
    style.map("Nav.TButton", background=[("active", SURFACE)], bordercolor=[("!disabled", BORDER_STRONG)])

    style.configure("Danger.TButton", background=DANGER_SOFT, foreground=DANGER,
                     font=(family, 10), padding=(10, 6), borderwidth=0, relief="flat")
    style.map("Danger.TButton", background=[("active", DANGER_SOFT_ACTIVE)])

    style.configure("TEntry", fieldbackground=FIELD_BG, foreground=TEXT_PRIMARY, padding=6,
                     borderwidth=1, relief="flat", bordercolor=BORDER_STRONG,
                     insertcolor=TEXT_PRIMARY)
    style.configure("TCombobox", fieldbackground=FIELD_BG, background=FIELD_BG, foreground=TEXT_PRIMARY,
                     padding=6, borderwidth=1, relief="flat", arrowsize=14)
    style.map("TCombobox", fieldbackground=[("readonly", FIELD_BG)],
              selectbackground=[("readonly", FIELD_BG)], selectforeground=[("readonly", TEXT_PRIMARY)],
              foreground=[("readonly", TEXT_PRIMARY)])

    style.configure("Big.TLabel", background=PANEL_BG, foreground=TEXT_PRIMARY, font=(family, 12))
    style.configure("Big.TEntry", fieldbackground=FIELD_BG, foreground=TEXT_PRIMARY, padding=10,
                     borderwidth=1, relief="flat", bordercolor=BORDER_STRONG,
                     insertcolor=TEXT_PRIMARY, font=(family, 12))
    style.configure("Big.TCombobox", fieldbackground=FIELD_BG, background=FIELD_BG, foreground=TEXT_PRIMARY,
                     padding=10, borderwidth=1, relief="flat", arrowsize=16, font=(family, 12))
    style.map("Big.TCombobox", fieldbackground=[("readonly", FIELD_BG)],
              selectbackground=[("readonly", FIELD_BG)], selectforeground=[("readonly", TEXT_PRIMARY)],
              foreground=[("readonly", TEXT_PRIMARY)])
    style.configure("Big.TCheckbutton", background=PANEL_BG, foreground=TEXT_PRIMARY, font=(family, 12))

    style.configure("TRadiobutton", background=PANEL_BG, foreground=TEXT_PRIMARY, font=(family, 10))
    style.configure("TCheckbutton", background=PANEL_BG, foreground=TEXT_PRIMARY, font=(family, 10))
    # The "clam" base theme's own Checkbutton/Radiobutton style swaps in a
    # bright default background the moment the mouse is over it (its
    # built-in "active" state color, never overridden above) -- jarring
    # against a themed, often-dark panel. Pinning "active" back to the
    # same PANEL_BG as everything else removes that flash entirely rather
    # than just picking a softer replacement color.
    style.map("TCheckbutton", background=[("active", PANEL_BG)])
    style.map("Big.TCheckbutton", background=[("active", PANEL_BG)])
    style.map("TRadiobutton", background=[("active", PANEL_BG)])

    # Tab bar: ttk.Notebook's own native tab strip is square-cornered with
    # no way to round it short of per-theme 9-slice image assets (this app
    # has none, deliberately -- see requirements.txt) or replacing it with
    # hand-drawn RoundedButton toggles the way MainWindow._build_body does
    # (its own tab_bar row, driving this same notebook via .select()).
    #
    # -tabposition is a real ttk::notebook option, but only settable on the
    # widget instance itself (self.notebook.configure(tabposition=...)) --
    # style.configure() silently accepts and stores an option name it
    # doesn't recognize without raising, so an earlier attempt to hide the
    # native strip this way did nothing and just left both tab rows
    # showing at once ("duplicate tabs"). Emptying "TNotebook.Tab"'s own
    # element layout is the real, widely-used fix: with no elements to
    # draw, every native tab collapses to zero size, while every other
    # Notebook mechanic (.add/.tab/.select, hidden-vs-normal panel state,
    # <<NotebookTabChanged>>) keeps working underneath exactly as before --
    # none of that lives in the Tab element's layout.
    style.configure(
        "TNotebook",
        background=APP_BG,
        borderwidth=0,
        relief="flat",
        padding=0,
        lightcolor=APP_BG,
        darkcolor=APP_BG,
        bordercolor=APP_BG,
    )
    style.configure("TNotebook.Pane", background=APP_BG, borderwidth=0)
    style.layout("TNotebook.Tab", [])
    # clam's Notebook.client still draws a 3D square around the page even
    # with borderwidth=0; painting those edges in APP_BG hides the box.
    try:
        style.layout("TNotebook", [("Notebook.client", {"sticky": "nswe"})])
    except tk.TclError:
        pass

    apply_window_chrome(root)
    apply_window_opacity(root)
    return family


