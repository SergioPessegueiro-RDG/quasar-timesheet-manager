_system_is_dark_cache = None


def _detect_system_is_dark() -> bool:
    """Best-effort, once-per-run check of the OS's current light/dark
    appearance setting, cached after the first call -- this is checked
    only at startup, not polled live, so if the user flips their OS
    appearance while the app is open the "Match System Appearance" theme
    won't follow until the app is restarted. Falls back to dark (this
    app's own long-standing default look) on any unsupported platform or
    failed check -- a themed-wrong app beats one that crashes on
    startup."""
    global _system_is_dark_cache
    if _system_is_dark_cache is not None:
        return _system_is_dark_cache
    is_dark = True
    if sys.platform == "darwin":
        try:
            result = subprocess.run(
                ["defaults", "read", "-g", "AppleInterfaceStyle"],
                capture_output=True, text=True, timeout=2,
            )
            # macOS only *sets* this key when Dark mode is active -- a
            # missing key (non-zero exit, empty stdout) means Light mode.
            is_dark = result.returncode == 0 and result.stdout.strip().lower() == "dark"
        except Exception:
            pass
    elif sys.platform == "win32":
        try:
            import winreg
            key = winreg.OpenKey(
                winreg.HKEY_CURRENT_USER,
                r"Software\Microsoft\Windows\CurrentVersion\Themes\Personalize",
            )
            value, _ = winreg.QueryValueEx(key, "AppsUseLightTheme")
            is_dark = value == 0
        except Exception:
            pass
    _system_is_dark_cache = is_dark
    return is_dark


def get_theme(theme_id: str) -> dict:
    """Look up a theme's {label, description, palette} by id, including
    the special "custom" id -- which isn't a fixed entry in THEMES, but is
    built live from whatever set_custom_seeds() last stored, so it always
    reflects the user's current picks even before they've hit Save."""
    theme_id = resolve_theme_id(theme_id)
    if theme_id == CUSTOM_THEME_ID:
        return {
            "label": "Custom",
            "category": "Custom",
            "description": "Your own palette -- pick a background, panel, text, and accent "
                            "color below and the rest is filled in to match.",
            "palette": derive_palette(**_custom_seeds),
        }
    if theme_id == SYSTEM_THEME_ID:
        seeds = _SYSTEM_SEEDS_DARK if _detect_system_is_dark() else _SYSTEM_SEEDS_LIGHT
        return {
            "label": "Auto",
            "category": "System",
            "description": "Follows your Mac or Windows light/dark setting — "
                            "White or Dark Mode. Checked once when the app starts; "
                            "switching your OS appearance while the app is open won't "
                            "change it until you restart.",
            "palette": derive_palette(**seeds),
        }
    return THEMES[theme_id]


def resolve_theme_id(value) -> str:
    """Turn a stored settings value (a current theme id, a legacy "light"/
    "dark" mode string or old palette id, or anything else/missing) into
    a valid theme id -- one of the twenty curated ids or "custom"."""
    if value == CUSTOM_THEME_ID or value == SYSTEM_THEME_ID or value in THEMES:
        return value
    if value in _LEGACY_MODE_MAP:
        return _LEGACY_MODE_MAP[value]
    return DEFAULT_THEME_ID


